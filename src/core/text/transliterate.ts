  А: "A",
  Б: "B",
  В: "V",
  Г: "G",
  Ґ: "G",
  Д: "D",
  Е: "E",
  Ё: "E",
  Є: "YE",
  Ж: "ZH",
  З: "Z",
  И: "I",
  І: "I",
  Ї: "YI",
  Й: "Y",
  К: "K",
  Л: "L",
  М: "M",
