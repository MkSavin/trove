import { dirname, resolve } from "node:path";
import { CONFIG_FILE } from "../core/config/load.ts";
import { git } from "../core/git/git.ts";
import { runRules } from "../core/rules/run.ts";
import { findUp, locateStore } from "../core/store/locate.ts";
import { openStore } from "../core/store/open.ts";
import { relativePath } from "../core/store/paths.ts";
import { syncStore } from "../core/sync/sync.ts";

/** The part of an assistant's hook input trove reads: Claude Code sends `file_path`, Kimi Code `path`. */
export type HookInput = {
  cwd?: string;
  tool_input?: { file_path?: string; path?: string };
  stop_hook_active?: boolean;
};

/** 0 quiet, 1 a notice shown to the user, 2 feedback the model must act on. */
export type HookReply = { code: 0 | 1 | 2; message: string };

const QUIET: HookReply = { code: 0, message: "" };

/** After an edit to a Markdown file of a store: its errors go back to the model. */
export const afterEdit = async (input: HookInput): Promise<HookReply> => {
  const edited = input.tool_input?.file_path ?? input.tool_input?.path;
  if (!edited?.endsWith(".md")) return QUIET;
  const path = resolve(input.cwd ?? process.cwd(), edited);
  const root = findUp(dirname(path), CONFIG_FILE);
  if (!root) return QUIET;

  const store = await openStore({ cwd: root, store: root });
  const rel = relativePath(root, path);
  if (Object.values(store.config.reports).some((report) => report.output === rel)) {
    return {
      code: 2,
      message: `${rel} is generated by trove and will be overwritten: edit the source documents instead`,
    };
  }
  const errors = runRules(store.rules, store.index).filter(
    (d) => d.file === rel && d.severity === "error",
  );
  if (errors.length === 0) return QUIET;
  const lines = errors.map((d) => `${rel}:${d.line ?? 1} ${d.rule}: ${d.message}`);
  return { code: 2, message: `trove check found errors in ${rel}:\n${lines.join("\n")}` };
};

/** At the end of a session: commit what was edited by hand, if the store syncs and is green. */
export const atStop = async (input: HookInput): Promise<HookReply> => {
  if (input.stop_hook_active || !input.cwd) return QUIET;
  const root = await locateStore(input.cwd).catch(() => undefined);
  if (!root) return QUIET;
  const store = await openStore({ cwd: root, store: root });
  if (store.config.sync === "off") return QUIET;
  if ((await git(root, ["status", "--porcelain"])).out === "") return QUIET;

  const errors = runRules(store.rules, store.index).filter((d) => d.severity === "error");
  if (errors.length > 0) {
    return {
      code: 1,
      message: `trove: ${errors.length} errors in the store, session edits not synced`,
    };
  }
  const result = await syncStore(store, "docs: sync session edits");
  const [warning] = result.warnings;
  return warning
    ? { code: 1, message: `trove: ${warning}` }
    : { code: 0, message: `trove: committed ${result.commit ?? "nothing"}` };
};
