import type { Anchor } from "./anchors.ts";
import { type Repo, type SourceFile, WORKAROUNDS_DIR, WORKAROUNDS_INDEX } from "./repo.ts";

type Workaround = { slug: string; file: SourceFile; head: ReadonlyMap<string, string> };

const HEAD = /^---\n([\s\S]*?)\n---(?:\n|$)/;
const VERIFIED = /\bChecked: INV:|\bNot checked automatically: \S/;

const slugOf = (file: SourceFile): string =>
  file.path.slice(WORKAROUNDS_DIR.length + 1).replace(/\.md$/, "");

const readHead = (text: string): ReadonlyMap<string, string> =>
  new Map(
    (HEAD.exec(text)?.[1] ?? "").split("\n").flatMap((line) => {
      const at = line.indexOf(": ");
      return at < 0 ? [] : [[line.slice(0, at), line.slice(at + 2).trim()]];
    }),
  );

const workaroundsOf = ({ docs }: Repo): Workaround[] =>
  docs
    .filter((doc) => doc.path.startsWith(`${WORKAROUNDS_DIR}/`))
    .map((file) => ({ slug: slugOf(file), file, head: readHead(file.text) }));

const anchorsOf = (all: readonly Anchor[]): Map<string, Anchor[]> =>
  Map.groupBy(
    all.filter((anchor) => anchor.namespace === "WORKAROUND"),
    (anchor) => anchor.id,
  );

const docProblems = (
  { slug, file, head }: Workaround,
  anchors: ReadonlyMap<string, readonly Anchor[]>,
): string[] => {
  const none = head.get("code") === "none";
  return [
    ...(head.get("anchor") === `WORKAROUND:${slug}`
      ? []
      : [`${file.path}: frontmatter needs anchor: WORKAROUND:${slug}`]),
    ...(head.get("rule") ? [] : [`${file.path}: frontmatter needs rule:`]),
    ...(none && !head.get("why") ? [`${file.path}: "code: none" needs "why:"`] : []),
    ...(none && anchors.has(slug) ? [`${file.path}: "code: none" but the code has anchors`] : []),
    ...(!none && !anchors.has(slug) ? [`${file.path}: no @anchor WORKAROUND:${slug} in code`] : []),
    ...(VERIFIED.test(file.text)
      ? []
      : [`${file.path}: needs "Checked: INV:..." or "Not checked automatically: <reason>"`]),
  ];
};

const anchorProblems = (anchor: Anchor, slugs: ReadonlySet<string>): string[] => {
  const where = `${anchor.file.path}:${anchor.line}`;
  return [
    ...(slugs.has(anchor.id) ? [] : [`${where}: WORKAROUND:${anchor.id} has no document`]),
    ...(anchor.reason ? [] : [`${where}: WORKAROUND:${anchor.id} needs its reason on this line`]),
  ];
};

const codeCell = (
  { slug, head }: Workaround,
  anchors: ReadonlyMap<string, readonly Anchor[]>,
): string => {
  if (head.get("code") === "none") return `none: ${head.get("why") ?? ""}`;
  const paths = new Set((anchors.get(slug) ?? []).map((anchor) => anchor.file.path));
  return [...paths]
    .toSorted()
    .map((path) => `\`${path}\``)
    .join(", ");
};

const cell = (text: string): string => text.replaceAll("|", "\\|");

export const renderWorkaroundIndex = (repo: Repo, all: readonly Anchor[]): string => {
  const anchors = anchorsOf(all);
  const rows = workaroundsOf(repo)
    .toSorted((a, b) => a.slug.localeCompare(b.slug))
    .map((workaround) => {
      const { slug, head } = workaround;
      const link = `[${slug}](workarounds/${slug}.md)`;
      return `| ${link} | ${cell(head.get("rule") ?? "")} | ${cell(codeCell(workaround, anchors))} |`;
    });
  return [
    "<!-- Generated by `bun scripts/check-docs.ts --write`. Do not edit. -->",
    "# Workarounds",
    "",
    "Platform quirks the code protects itself from. Never remove one until its symptom is reproduced on that platform, and check a change to one on every platform CI runs.",
    "",
    "| workaround | rule | code |",
    "| ---------- | ---- | ---- |",
    ...rows,
    "",
  ].join("\n");
};

export const checkWorkarounds = (repo: Repo, all: readonly Anchor[]): string[] => {
  const anchors = anchorsOf(all);
  const workarounds = workaroundsOf(repo);
  const slugs = new Set(workarounds.map(({ slug }) => slug));
  const index = repo.docs.find((doc) => doc.path === WORKAROUNDS_INDEX);
  return [
    ...workarounds.flatMap((workaround) => docProblems(workaround, anchors)),
    ...[...anchors.values()].flat().flatMap((anchor) => anchorProblems(anchor, slugs)),
    ...(index?.text === renderWorkaroundIndex(repo, all)
      ? []
      : [`${WORKAROUNDS_INDEX} is stale: run bun scripts/check-docs.ts --write`]),
  ];
};
